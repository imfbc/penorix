  var STORE = "penorix-lang";
  var lang = "en";
  try { var s = localStorage.getItem(STORE); if (s === "ko" || s === "en") lang = s; } catch (e) {}

  function t(key) { return (D[lang] && D[lang][key]) || D.en[key] || key; }

  function apply() {
    var root = document.documentElement;
    root.lang = lang;
    var nodes = document.querySelectorAll("[data-i18n]");
    for (var i = 0; i < nodes.length; i++) {
      var el = nodes[i], k = el.getAttribute("data-i18n");
      if (el.hasAttribute("data-i18n-html")) el.innerHTML = t(k); else el.textContent = t(k);
    }
    var attrs = document.querySelectorAll("[data-i18n-attr]");
    for (var j = 0; j < attrs.length; j++) {
      attrs[j].getAttribute("data-i18n-attr").split(",").forEach(function (pair) {
        var p = pair.split(":");
        attrs[j].setAttribute(p[0], t(p[1]));
      });
    }
    var page = document.body.getAttribute("data-page");
    if (page) {
      document.title = t("meta." + page + ".title");
      var m = document.querySelector('meta[name="description"]');
      if (m) m.setAttribute("content", t("meta." + page + ".desc"));
      var og = document.querySelector('meta[property="og:title"]');
      if (og) og.setAttribute("content", t("meta." + page + ".title"));
    }
    document.dispatchEvent(new CustomEvent("penorix:lang", { detail: lang }));
  }

  function set(next) {
    lang = next === "ko" ? "ko" : "en";
    try { localStorage.setItem(STORE, lang); } catch (e) {}
    apply();
  }

  window.PenorixI18n = { t: t, apply: apply, set: set, get: function () { return lang; } };
  document.documentElement.lang = lang;
